// Builds the unpacked extension into dist/: bundles the TypeScript entry points with
// esbuild, compiles the Tailwind stylesheet for the extension pages, copies static
// files, and writes _locales from src/locales.ts.

import { execFileSync } from "node:child_process";
import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import * as esbuild from "esbuild";
import { locales } from "../src/locales.ts";

const root = new URL("..", import.meta.url).pathname;
const dist = join(root, "dist");
const watch = process.argv.includes("--watch");

async function writeLocales(): Promise<void> {
  for (const [lang, messages] of Object.entries(locales)) {
    const dir = join(dist, "_locales", lang);
    await mkdir(dir, { recursive: true });
    const json = Object.fromEntries(
      Object.entries(messages).map(([key, message]) => [key, { message }]),
    );
    await writeFile(join(dir, "messages.json"), `${JSON.stringify(json, null, 2)}\n`);
  }
}

async function copyStatic(): Promise<void> {
  await cp(join(root, "static"), dist, { recursive: true });
  // MIT requires the license notice to travel with every copy, including the store package.
  await cp(join(root, "LICENSE"), join(dist, "LICENSE.txt"));
  for (const file of ["options.html", "popup.html"]) {
    await cp(join(root, "src/pages", file), join(dist, file));
  }
}

// Every entry point is a classic script (content scripts cannot be ES modules), so all
// bundles are IIFEs.
const shared: esbuild.BuildOptions = {
  absWorkingDir: root,
  outdir: dist,
  bundle: true,
  format: "iife",
  target: "chrome121",
  sourcemap: false,
  jsx: "automatic",
  define: {
    __E2E__: JSON.stringify(process.env.MLG_E2E === "1"),
    // E2E builds only: pin the UI language (e.g. MLG_LANG=en) instead of following Chrome.
    __E2E_LANG__: JSON.stringify(process.env.MLG_E2E === "1" ? (process.env.MLG_LANG ?? "") : ""),
    "process.env.NODE_ENV": '"production"',
  },
  metafile: true,
  logLevel: "info",
};

// The scripts that run inside the webmail page and in the background are our own code
// only. They stay unminified so anyone can read exactly what runs next to their mail.
const ownCode: esbuild.BuildOptions = {
  ...shared,
  entryPoints: { content: "src/content/index.ts", background: "src/background/index.ts" },
  minify: false,
  legalComments: "none",
};

// The settings page and the popup bundle React and shadcn/ui. Minifying them cuts the
// popup from about 850 KB to about 200 KB, so it opens without a visible delay.
// Third-party license headers are kept, and THIRD_PARTY_NOTICES.txt lists every bundled package.
const pages: esbuild.BuildOptions = {
  ...shared,
  entryPoints: { options: "src/pages/options.tsx", popup: "src/pages/popup.tsx" },
  minify: true,
  legalComments: "inline",
};

/** Writes the name, version, license and license text of every package bundled into dist/. */
async function writeThirdPartyNotices(metafiles: esbuild.Metafile[]): Promise<void> {
  const dirs = new Set<string>();
  for (const meta of metafiles) {
    // Only inputs that contributed bytes: the radix-ui index lists every primitive,
    // but tree shaking drops the unused ones.
    const used = Object.values(meta.outputs).flatMap((o) =>
      Object.entries(o.inputs)
        .filter(([, v]) => v.bytesInOutput > 0)
        .map(([k]) => k),
    );
    for (const input of used) {
      const m = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
      if (m) dirs.add(join(root, m[1]));
    }
  }
  const sections: string[] = [];
  for (const dir of [...dirs].sort()) {
    const pkg = JSON.parse(await readFile(join(dir, "package.json"), "utf8"));
    const files = await readdir(dir);
    const licenseFile = files.find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
    const noticeFile = files.find((f) => /^notice(\.|$)/i.test(f));
    const text = licenseFile ? await readFile(join(dir, licenseFile), "utf8") : "";
    const notice = noticeFile ? await readFile(join(dir, noticeFile), "utf8") : "";
    sections.push(
      [`${pkg.name}@${pkg.version} (${pkg.license ?? "see package"})`, text.trim(), notice.trim()]
        .filter(Boolean)
        .join("\n\n"),
    );
  }
  const header =
    "Mail Link Guard bundles the following third-party packages in options.js and popup.js.\n" +
    "pages.css is generated by Tailwind CSS (MIT License).\n";
  await writeFile(
    join(dist, "THIRD_PARTY_NOTICES.txt"),
    `${header}\n${sections.join(`\n\n${"-".repeat(72)}\n\n`)}\n`,
  );
}

await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });
await copyStatic();
await writeLocales();

function buildCss(): void {
  execFileSync(
    join(root, "node_modules/.bin/tailwindcss"),
    ["-i", "src/pages/globals.css", "-o", join(dist, "pages.css"), "--minify"],
    { cwd: root, stdio: "inherit" },
  );
}
buildCss();

if (watch) {
  await Promise.all([ownCode, pages].map(async (o) => (await esbuild.context(o)).watch()));
} else {
  const results = await Promise.all([esbuild.build(ownCode), esbuild.build(pages)]);
  await writeThirdPartyNotices(results.map((r) => r.metafile as esbuild.Metafile));
}
